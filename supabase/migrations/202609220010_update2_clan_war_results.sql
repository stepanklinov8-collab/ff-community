create or replace function public.u2_war_games_init() returns trigger language plpgsql security definer set search_path=public as $$
begin
 if new.game_count<1 or new.wins_required<1 or new.game_count<2*new.wins_required-1 or cardinality(new.maps)<>new.game_count
 or not new.maps<@array['bermuda','nexterra','solara','purgatory','kalahari']::text[] then raise exception 'Проверьте игры и число побед в серии';end if;
 insert into public.clan_war_games(clan_war_id,game_number,map_name) select new.id,n,new.maps[n] from generate_series(1,new.game_count) n;
 return new;
end $$;
create trigger u2_war_games_init after insert on public.clan_wars for each row execute function public.u2_war_games_init();

create or replace function public.u2_war_role(p_actor uuid,p_war uuid,p_check_window boolean default true) returns text
language plpgsql security definer set search_path=public as $$
declare w public.clan_wars%rowtype;
begin
 select * into w from public.clan_wars where id=p_war;
 if w.id is null then raise exception 'КВ не найдено';end if;
 if public.is_full_admin(p_actor) then return 'admin';end if;
 if not coalesce(public.can_manage_team(w.creator_team_id,p_actor) or public.can_manage_team(w.opponent_team_id,p_actor),false) then raise exception 'Нет прав на результаты КВ';end if;
 if p_check_window and w.result_first_published_at is not null and now()>=w.result_first_published_at+interval '7 days' then raise exception 'Срок исправления результатов истёк';end if;
 return 'organizer';
end $$;

create or replace function public.u2_war_roster_guard() returns trigger language plpgsql security definer set search_path=public as $$
declare w public.clan_wars%rowtype;
begin
 select * into w from public.clan_wars where id=coalesce(new.clan_war_id,old.clan_war_id) for update;
 if tg_op='UPDATE' and new.player_ids=old.player_ids and new.team_id=old.team_id then return new;end if;
 if current_setting('omcite.war_configuration',true) is distinct from w.id::text and w.result_revision>0 then raise exception 'Нельзя менять состав после начала внесения результатов';end if;
 if current_setting('omcite.war_configuration',true) is distinct from w.id::text
 and now()>=w.scheduled_at-interval '10 minutes'
 and not public.is_full_admin(coalesce(auth.uid(),new.submitted_by,old.submitted_by)) then raise exception 'Состав уже закрыт. Обратитесь к администратору';end if;
 if w.status not in('open','pending','agreed') then raise exception 'Состав КВ уже закрыт';end if;
 if tg_op<>'DELETE' then
 new.roster_snapshot:=(select coalesce(jsonb_agg(jsonb_build_object('id',p.id,'nickname',p.nickname,'gameId',p.game_id)),'[]') from public.profiles p where p.id=any(new.player_ids));
 select name into new.name_snapshot from public.teams where id=new.team_id;
 end if;
 update public.clan_wars set configuration_revision=configuration_revision+1 where id=w.id;
 if tg_op='DELETE' then return old;end if;return new;
end $$;
create trigger u2_war_roster_guard before insert or update or delete on public.clan_war_rosters for each row execute function public.u2_war_roster_guard();

create or replace function public.u2_war_results(p_actor uuid,p_war uuid,p_action text,p_revision integer,p_configuration integer,p_request uuid,p_hash text,p_draft jsonb default null,p_candidate jsonb default null,p_team uuid default null)
returns jsonb language plpgsql security definer set search_path=public as $$
declare w public.clan_wars%rowtype; op public.competition_operations%rowtype; role text; response jsonb; revision_value integer; approved boolean:=false;
 candidate jsonb; warning jsonb; old_warning record; target record; market record; standing jsonb; own_wins integer; rival_wins integer; own_kills integer; outcome text;
begin
 perform pg_advisory_xact_lock(hashtextextended('competition-publication',0));
 select * into op from public.competition_operations where request_id=p_request;
 if op.request_id is not null then
 if op.actor_id<>p_actor or op.scope_id<>p_war or op.request_hash<>p_hash then raise exception 'Ключ запроса уже использован';end if;return op.response;end if;
 select * into w from public.clan_wars where id=p_war for update;
 role:=public.u2_war_role(p_actor,p_war);
 if w.status not in('agreed','completed') or w.opponent_team_id is null then raise exception 'Сначала согласуйте КВ с соперником';end if;
 if w.result_revision<>p_revision or w.configuration_revision<>p_configuration then raise exception 'Конфликт версии: обновите результаты КВ';end if;
 revision_value:=w.result_revision;
 if p_action in('draft','publish') then
 if p_draft is null or p_action='publish' and p_candidate is null then raise exception 'Заполните результаты';end if;
 if p_action='draft' and w.result_first_published_at is not null then raise exception 'Исправление отправляется целиком';end if;
 p_draft:=public.u2_normalize_warning_ids(p_draft,null,p_war);
 revision_value:=revision_value+1;
 update public.clan_wars set result_draft=p_draft,result_candidate=p_candidate,result_revision=revision_value,result_approval_a=null,result_approval_b=null,result_disputed=false where id=p_war;
 if p_action='publish' then
 perform public.u2_notify_target('team',w.creator_team_id,'war-review-a:'||w.id||':'||revision_value,'Результаты КВ ждут подтверждения',w.title,'/clan-wars/'||w.id||'/results');
 perform public.u2_notify_target('team',w.opponent_team_id,'war-review-b:'||w.id||':'||revision_value,'Результаты КВ ждут подтверждения',w.title,'/clan-wars/'||w.id||'/results');end if;
 elsif p_action in('approve','dispute','resolve') then
 if w.result_candidate is null then raise exception 'Сначала отправьте заполненную версию на подтверждение';end if;
 if p_action='resolve' then
 if role<>'admin' then raise exception 'Требуются права администратора';end if;approved:=true;
 else
 if p_team is null or p_team not in(w.creator_team_id,w.opponent_team_id) or not exists(select 1 from public.team_members where team_id=p_team and user_id=p_actor and role_in_team in('leader','senior_deputy','deputy')) then raise exception 'Нет прав подтверждать за эту сторону';end if;
 if p_action='dispute' then
 update public.clan_wars set result_disputed=true,result_approval_a=null,result_approval_b=null where id=p_war;
 for target in select distinct ur.user_id from public.user_roles ur where ur.role in('admin','superadmin') loop
 perform public.u2_notify_target('player',target.user_id,'war-dispute:'||w.id||':'||revision_value,'Спор о результате КВ',w.title,'/clan-wars/'||w.id||'/results');end loop;
 else
 if w.result_disputed then raise exception 'Спор рассматривает администратор; отправьте новую версию или дождитесь решения';end if;
 update public.clan_wars set result_approval_a=case when p_team=creator_team_id then result_revision else result_approval_a end,
 result_approval_b=case when p_team=opponent_team_id then result_revision else result_approval_b end where id=p_war returning * into w;
 approved:=coalesce(w.result_approval_a=w.result_revision and w.result_approval_b=w.result_revision,false);
 end if;end if;
 else raise exception 'Неизвестное действие';end if;
 if approved then
 candidate:=w.result_candidate;
 -- Reconfirming the same revision is harmless, including wallet and warning effects.
 if w.result_published_revision is distinct from revision_value then
 perform public.u2_sync_duels(candidate,coalesce(w.completed_at,now()),null,null,p_war);
 for old_warning in select * from public.warnings where clan_war_id=p_war and update2 and cancelled_at is null loop
 if not exists(select 1 from jsonb_array_elements(w.result_draft->'warnings') x where (x->>'id')::uuid=old_warning.id) then perform public.u2_cancel_warning(p_actor,old_warning.id,'Исправление результата КВ');end if;end loop;
 for warning in select value from jsonb_array_elements(w.result_draft->'warnings') loop
 perform public.u2_write_warning(p_actor,null,warning||jsonb_build_object('clanWarId',p_war));end loop;
 for target in select distinct target_type,target_id from public.warnings where clan_war_id=p_war and update2 loop
 perform public.u2_check_warning_thresholds(target.target_type,target.target_id,p_actor);perform public.u2_recalculate_reputation(target.target_type,target.target_id);end loop;
 perform public.u2_settle_war_results(p_actor,p_war,candidate);
 update public.clan_wars set status='completed',completed_at=coalesce(completed_at,now()),result_published=candidate,result_published_revision=revision_value,result_first_published_at=coalesce(result_first_published_at,now()),
 result_corrected_at=case when result_first_published_at is not null then now() end,result_disputed=false where id=p_war;
 perform public.u2_notify_target('team',w.creator_team_id,'war-confirmed-a:'||w.id||':'||revision_value,'Результаты КВ подтверждены',w.title,'/clan-wars/'||w.id);
 perform public.u2_notify_target('team',w.opponent_team_id,'war-confirmed-b:'||w.id||':'||revision_value,'Результаты КВ подтверждены',w.title,'/clan-wars/'||w.id);
 end if;end if;
 response:=jsonb_build_object('success',true,'revision',revision_value,'published',approved,'awaitingApproval',not approved and p_action='publish');
 insert into public.competition_operations(request_id,actor_id,scope_id,request_hash,response) values(p_request,p_actor,p_war,p_hash,response);
 insert into public.competition_action_log(actor_id,scope_id,action,metadata) values(p_actor,p_war,'war_'||p_action,jsonb_build_object('revision',revision_value,'teamId',p_team,'published',approved));
 return response;
end $$;

